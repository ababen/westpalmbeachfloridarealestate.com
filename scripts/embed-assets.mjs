// Bundles the built site in dist/ into worker/assets.js so the Worker can serve it
// without a separate static-asset upload.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const root = new URL('../dist/', import.meta.url).pathname;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

// Building, neighborhood and hero images are served from the R2 bucket instead (scripts/upload-images.mjs), keeping the
// Worker under its size limit.
const R2_PREFIXES = ['images/condos/', 'images/neighborhoods/', 'images/hero/'];

const assets = {};
for await (const file of walk(root)) {
  const key = relative(root, file);
  if (R2_PREFIXES.some((p) => key.startsWith(p))) continue;
  assets[key] = (await readFile(file)).toString('base64');
}

await writeFile(
  new URL('../worker/assets.js', import.meta.url),
  `// Generated by scripts/embed-assets.mjs — do not edit.\nexport default ${JSON.stringify(assets)};\n`,
);
console.log(`Embedded ${Object.keys(assets).length} files`);
